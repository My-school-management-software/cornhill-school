import test from "node:test";
import assert from "node:assert/strict";
import { createPostgresAdmissionsRepository } from "../src/db/admissions-repositories.mjs";

test("admission repository commits learner, guardian, enrolment and audit as one transaction", async () => {
  const calls=[];
  const client={
    async query(sql,params=[]){calls.push({sql,params});if(sql.startsWith("INSERT INTO cornhill_school.learners"))return {rows:[{id:"11111111-1111-4111-8111-111111111111",pupil_code:"CH-2026-000001"}]};return {rows:[]};},
    release(){calls.push({sql:"RELEASE"});}
  };
  const repo=createPostgresAdmissionsRepository({async connect(){return client;}});
  const result=await repo.registerLearner({
    actorStaffId:"22222222-2222-4222-8222-222222222222",classId:"33333333-3333-4333-8333-333333333333",
    firstName:"Amina",middleName:null,lastName:"Nabirye",gender:"Female",dateOfBirth:null,lin:"UG-001",
    admissionDate:"2026-01-12",learnerType:"Day",previousSchool:null,p7IndexNumber:null,isBursary:true,
    bursaryFeeUgx:50000,bursaryCategory:"Need-based",bursaryReason:null,takesBreakfast:false,takesLunch:true,
    reason:"New admission",guardian:{name:"Parent One",relationship:"Mother",phone:"+256700000001",whatsapp:null,email:null,smsOptIn:false,whatsappOptIn:false}
  });
  assert.equal(result.pupil_code,"CH-2026-000001");
  assert.equal(calls[0].sql,"BEGIN");
  assert.equal(calls.filter(x=>x.sql.startsWith("INSERT INTO")).length,4);
  assert.equal(calls.at(-2).sql,"COMMIT");
  assert.equal(calls.at(-1).sql,"RELEASE");
  assert.equal(calls.some(x=>x.sql.includes("pupil_code")&&x.sql.startsWith("INSERT")),false,"pupil code must be generated by the database");
});

test("admission repository rolls back every partial write after a failure", async () => {
  const calls=[];
  const client={async query(sql){calls.push(sql);if(sql.startsWith("INSERT INTO cornhill_school.guardian_contacts"))throw new Error("guardian insert failed");if(sql.startsWith("INSERT INTO cornhill_school.learners"))return {rows:[{id:"11111111-1111-4111-8111-111111111111",pupil_code:"CH-2026-000002"}]};return {rows:[]};},release(){}};
  const repo=createPostgresAdmissionsRepository({async connect(){return client;}});
  await assert.rejects(repo.registerLearner({guardian:{name:"Guardian"}}),/guardian insert failed/);
  assert.equal(calls.at(-1),"ROLLBACK");
  assert.equal(calls.includes("COMMIT"),false);
});
